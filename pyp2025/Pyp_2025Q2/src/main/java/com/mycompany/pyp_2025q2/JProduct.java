    private void saveProductData() {

  if (txtAreaOutput.getText().isEmpty()) {       // nothing loaded yet​
    JOptionPane.showMessageDialog(this, "Load the data first.");
    return;
  }
  // try-with-resources closes the file automatically​
  try (PrintWriter out = new PrintWriter(new FileWriter("data.txt"))) {
    out.println("DATA LOG");
    out.println("**********************************");
    out.print(txtAreaOutput.getText());          // report body​
    out.println("**********************************");
    JOptionPane.showMessageDialog(this, "Saved to data.txt");
  } catch (IOException ex) {
    JOptionPane.showMessageDialog(this, "Save failed: " + ex.getMessage());
  }
}
