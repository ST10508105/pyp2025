private void loadProductData() {
  ProductSales sales = new ProductSales();  // data held in memory​

  StringBuilder report = new StringBuilder();

  report.append("Total Sales: " + sales.GetTotalSales() + "\n");

  report.append(String.format("Average Sales: %.0f\n",

                              sales.GetAverageSales()));

  report.append("Sales over limit: " + sales.GetSalesOverLimit() + "\n");

  report.append("Sales under limit: " + sales.GetSalesUnderLimit() + "\n");

  txtAreaOutput.setText(report.toString());
  lblYearsProcessed.setText("Years Processed: " + sales.GetProductsProcessed());
}
    
